// Writes docs/class-search-check.md from the latest run in data/checks/ (made by check-class-search.mjs).
// Run: node data/scripts/report-class-search-check.mjs
// Reads only. The report has no timestamps of its own, so the same check file always gives the same report.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const read = (p) => JSON.parse(readFileSync(here(p), 'utf8'));

// ─── Latest run: <date>.json, <date>-2.json, ... (applied-<date>.json files are not runs) ───
const runs = readdirSync(here('../checks/'))
  .map((f) => f.match(/^(\d{4}-\d{2}-\d{2})(?:-(\d+))?\.json$/)?.slice(0, 3))
  .filter(Boolean)
  .map(([file, date, n]) => ({ file, date, n: Number(n ?? 1) }))
  .sort((a, b) => a.date.localeCompare(b.date) || a.n - b.n);
if (!runs.length) { console.error('No check files in data/checks/. Run check-class-search.mjs first.'); process.exit(1); }
const latest = runs.at(-1);
const run = read(`../checks/${latest.file}`);
const { meta, sections } = run;

// Titles for readability (read only)
const titles = new Map();
for (const f of ['../courses.json', '../courses-extra.json']) for (const c of read(f)) titles.set(c.id, { code: c.code, title: c.title });
const label = (id, code) => {
  const t = titles.get(id);
  return t ? `${t.code} ${t.title}` : `${code} (no class record: ${id})`;
};
const cell = (s) => String(s ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ');

// Flatten
const rows = [];
for (const [courseId, secs] of Object.entries(sections)) for (const [section, e] of Object.entries(secs)) rows.push({ courseId, section, ...e });
const byCourse = (list) => {
  const m = new Map();
  for (const r of list) (m.get(r.courseId) ?? m.set(r.courseId, []).get(r.courseId)).push(r);
  return [...m].sort(([a, x], [b, y]) => label(a, x[0].code).localeCompare(label(b, y[0].code)));
};

const L = [];
L.push('# CU class search check', '');
L.push(`Generated by \`data/scripts/report-class-search-check.mjs\` from \`data/checks/${latest.file}\`. CU class search is the source of truth; a section it does not list yet is "pending", never wrong. See \`data/CHECKING.md\` for how to refresh this.`, '');
L.push(`- Checked: ${meta.checkedAt} (America/Denver)`, `- Input: ${meta.input}`, `- Term: ${meta.term} (srcdb ${meta.srcdb})`, `- Sections in the class search response: ${meta.classSearchSections}`, '');
L.push('## Counts', '', '| status | sections |', '| --- | --- |');
for (const s of ['confirmed', 'mismatch', 'pending', 'new', 'cancelled']) L.push(`| ${s} | ${meta.counts[s] ?? 0} |`);
L.push(`| **total** | ${rows.length} |`, '');

const STATUS_NOTE = {
  mismatch: 'In both, but a field differs. Class search value first.',
  pending: 'In our data but not in class search yet. Nothing is removed.',
  new: 'In class search but not in our data.',
  cancelled: 'Class search marks the section cancelled.',
};
for (const status of ['mismatch', 'pending', 'new', 'cancelled']) {
  const list = rows.filter((r) => r.status === status);
  L.push(`## ${status[0].toUpperCase()}${status.slice(1)} (${list.length})`, '', STATUS_NOTE[status], '');
  if (!list.length) { L.push('None.', ''); continue; }
  if (status === 'mismatch') L.push('| class | section | field | class search | ours |', '| --- | --- | --- | --- | --- |');
  else L.push('| class | sections | note |', '| --- | --- | --- |');
  for (const [id, recs] of byCourse(list)) {
    recs.sort((a, b) => a.section.localeCompare(b.section));
    if (status === 'mismatch') {
      for (const r of recs) for (const m of r.mismatchedFields) L.push(`| ${cell(label(id, r.code))} | ${r.section} | ${m.field} | ${cell(m.classSearch)} | ${cell(m.ours)} |`);
    } else {
      const notes = [...new Set(recs.flatMap((r) => r.notes))].join('; ');
      L.push(`| ${cell(label(id, recs[0].code))} | ${recs.map((r) => r.section).join(', ')} | ${cell(notes) || '(none)'} |`);
    }
  }
  L.push('');
}

// ─── Instructors that still differ ───────────────────────────────────────────
const instr = rows.filter((r) => r.mismatchedFields.some((m) => m.field === 'instructor'));
L.push(`## Instructor names that differ (${instr.length} sections)`, '');
L.push('Open items: our data (from the ATLAS sheet) and CU class search name different people or spell a name differently. The check ignores "A, B" vs "A/B", case, accents, and a first initial missing on one side, so each line is a real difference in the text, although some may be the same person (a longer surname, for example). Decide which is right, then fix the sheet or accept class search with `--apply` (see `data/CHECKING.md`).', '');
if (!instr.length) L.push('None.', '');
else {
  L.push('| class | sections | ours (sheet) | CU class search |', '| --- | --- | --- | --- |');
  for (const [id, recs] of byCourse(instr)) {
    const pairs = new Map();
    for (const r of recs) {
      const m = r.mismatchedFields.find((x) => x.field === 'instructor');
      const k = `${m.ours}\u0000${m.classSearch}`;
      (pairs.get(k) ?? pairs.set(k, []).get(k)).push(r.section);
    }
    for (const [k, secs] of pairs) {
      const [ours, theirs] = k.split('\u0000');
      L.push(`| ${cell(label(id, recs[0].code))} | ${secs.sort().join(', ')} | ${cell(ours)} | ${cell(theirs)} |`);
    }
  }
  L.push('');
}
const blank = rows.filter((r) => r.skipped.some((s) => s.startsWith('instructor:')));
L.push(`Not differences: ${blank.length} sections have no instructor in class search yet (shown as skipped, not mismatched).`, '');

writeFileSync(here('../../docs/class-search-check.md'), L.join('\n'));
console.log(`Wrote docs/class-search-check.md from data/checks/${latest.file}`);
