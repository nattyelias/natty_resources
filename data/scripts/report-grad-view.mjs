// Writes docs/grad-view.md: every class gradCourses() returns, and every class it leaves out.
// Run: node data/scripts/report-grad-view.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { defaultConfig, termContext } from '../../src/core/config.ts';
import { allCourses, gradCourses, gradReason } from '../../src/core/courses.ts';
import { upcomingTerms } from '../../src/core/terms.ts';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const read = (p) => JSON.parse(readFileSync(here(p), 'utf8'));
const ctx = termContext(defaultConfig);
const all = allCourses(read('../courses.json'), read('../courses-extra.json'));

const grad = gradCourses(all, ctx);
const inGrad = new Set(grad.map((g) => g.course.id));
const excluded = all.filter((c) => !inGrad.has(c.id));
const cell = (s) => String(s).replace(/\|/g, '/');

const L = [];
L.push('# Graduate view', '');
L.push('Generated by `data/scripts/report-grad-view.mjs` using `gradCourses()` in `src/core/courses.ts`. Nothing is labelled by hand: a class qualifies when its level is Grad or Grad/Focus, or its own code or a cross-list code on its sections in an upcoming term has a course number of 5000 or higher, and it is offered in an upcoming term.', '');
L.push('- **5000-level twin**: the class is cross-listed across the 5000 line (for example ATLS 4040 and ATLS 5040). Both sides of the pair are listed.');
L.push('- **grad-only**: it qualifies with no undergraduate counterpart.', '');
const count = (r) => grad.filter((g) => g.reason === r).length;
L.push(`${all.length} classes in total: ${grad.length} in the graduate view (${count('grad-only')} grad-only, ${count('5000-level twin')} 5000-level twin) and ${excluded.length} left out.`, '');

L.push('## 1. In the graduate view', '');
L.push('| code | title | reason | upcoming or not | independent study |', '| --- | --- | --- | --- | --- |');
for (const { course: c, reason } of [...grad].sort((a, b) => a.course.code.localeCompare(b.course.code) || a.course.title.localeCompare(b.course.title))) {
  L.push(`| ${c.code} | ${cell(c.title)} | ${reason} | upcoming (${upcomingTerms(c.termsOffered, ctx).join(', ')}) | ${c.independentStudy ? 'yes' : ''} |`);
}

L.push('', '## 2. Left out (undergrad-only or not offered in an upcoming term)', '');
L.push('| code | title | level | why left out |', '| --- | --- | --- | --- |');
for (const c of [...excluded].sort((a, b) => a.code.localeCompare(b.code) || a.title.localeCompare(b.title))) {
  const upcoming = upcomingTerms(c.termsOffered, ctx).length > 0;
  const why = !upcoming
    ? gradReason(c, ctx) ? 'would qualify, but not offered in an upcoming term' : `not offered in an upcoming term, and no 5000+ code in its data (${c.termsOffered.length ? 'ran ' + c.termsOffered.join(', ') : 'no terms'})`
    : 'undergrad-only: no 5000+ code and no Grad level';
  L.push(`| ${c.code} | ${cell(c.title)} | ${c.level || '(none)'} | ${why} |`);
}
writeFileSync(here('../../docs/grad-view.md'), L.join('\n') + '\n');
console.log(`Wrote docs/grad-view.md: ${grad.length} in, ${excluded.length} out`);
