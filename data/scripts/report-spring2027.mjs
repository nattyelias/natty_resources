// Writes docs/spring2027-conflicts.md from data/spring2027.json, data/courses.json and data/sources/2271.json.
// Run: node data/scripts/report-spring2027.mjs   (after merge-spring2027 and attach-spring2027)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { displayName, findClass } from './lib/match-spring2027.mjs';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const read = (p) => JSON.parse(readFileSync(here(p), 'utf8'));
const merged = read('../spring2027.json').sections;
const courses = read('../courses.json');
const pull = read('../sources/2271.json').sections;

const L = [];
const section = (title) => L.push('', `## ${title}`, '');
const secList = (recs) => recs.map((r) => r.section).join(', ');
const groupBy = (arr, f) => { const m = new Map(); for (const x of arr) { const k = f(x); (m.get(k) ?? m.set(k, []).get(k)).push(x); } return m; };
const label = (r) => `${r.courseCode} ${r.title}`;

const matched = new Map(); // key -> course
const unmatched = [];
for (const r of merged) {
  if (r.cancelled) continue;
  const m = findClass(r, courses);
  if (m.course) matched.set(r.key, m.course); else unmatched.push({ r, reason: m.reason });
}

L.push('# Spring 2027 merge: conflicts and gaps', '');
L.push('Generated by `data/scripts/report-spring2027.mjs` from `data/spring2027.json` (merged by `merge-spring2027.mjs`) and `data/courses.json` (updated by `attach-spring2027.mjs`).', '');
const c = merged.filter((r) => r.conflict);
L.push(`Totals: ${merged.length} sections. Both sources ${merged.filter((r) => r.source === 'both').length}, sheet only ${merged.filter((r) => r.source === 'sheet').length}, pull only ${merged.filter((r) => r.source === 'pull').length}. Day/time conflicts ${c.length}. Attached to a class in courses.json ${matched.size}, unmatched ${unmatched.length}.`);

// 1. Conflicts
section('1. Day and time conflicts');
if (!c.length) L.push('None. Where both sources list a section, the days and the 24-hour start and end agree for every one.');
for (const r of c) L.push(`- **${r.key}** ${r.title}: ${r.conflicts.map((x) => `${x.field}: sheet ${x.sheet} vs pull ${x.pull}`).join('; ')}`);

// 2. Instructor differences
section('2. Instructor differences (sheet value was used)');
L.push('The sheet wins for instructor. These are the sections where the sheet and the pull name someone different once both are written as "F. Last". Worth a look: the sheet may be wrong or the pull may be out of date.', '');
const norm = (s) => s.toLowerCase().replace(/\s+/g, ' ').trim();
const diffs = merged.filter((r) => r.instructorPull && norm(displayName(r.instructor)) !== norm(r.instructorPull));
if (!diffs.length) L.push('None.');
for (const [k, recs] of groupBy(diffs, (r) => r.courseCode)) {
  L.push(`- **${k}**`);
  for (const r of recs) L.push(`  - ${r.section} (${r.title}): sheet "${r.instructor}" (written "${displayName(r.instructor)}"), pull "${r.instructorPull}"`);
}
const blanks = merged.filter((r) => r.source === 'both' && r.instructorFrom === 'pull');
L.push('', `Sheet cell empty, pull name used (${blanks.length} sections found in both sources, mostly recitations): ${[...groupBy(blanks, (r) => r.courseCode)].map(([k, v]) => `${k} (${secList(v)})`).join('; ') || 'none'}.`);

// 3. Single-source
section('3. Single-source sections and classes');
L.push('### Sheet only (not in the pull)', '');
const sheetOnly = merged.filter((r) => r.source === 'sheet');
for (const r of sheetOnly) {
  const twin = merged.find((x) => x.source === 'pull' && x.courseCode === r.courseCode && x.days === r.days && r.start && x.start && x.start === r.start && x.end === r.end);
  L.push(`- **${r.key}** ${r.title}, ${r.sheetDays} ${r.time}${twin ? `. Possibly the same section as pull-only ${twin.key} (same day and time), just numbered differently` : ''}.`);
}
if (!sheetOnly.length) L.push('None.');
L.push('', '### Pull only (not on the sheet), by class', '');
const pullOnly = merged.filter((r) => r.source === 'pull');
const bothCodes = new Set(merged.filter((r) => r.source !== 'pull').map((r) => r.courseCode));
for (const [k, recs] of groupBy(pullOnly, (r) => r.courseCode)) {
  const all = !bothCodes.has(k);
  const timed = recs.filter((r) => r.start).length;
  L.push(`- **${k}** ${recs[0].title}: ${recs.length} section(s) (${secList(recs).length > 70 ? `${recs[0].section} to ${recs[recs.length - 1].section}` : secList(recs)}), ${all ? 'whole class missing from the sheet' : 'other sections are on the sheet'}${timed ? '' : ', no meeting time posted'}${matched.has(recs[0].key) ? `, attached to ${matched.get(recs[0].key).id}` : ''}.`);
}

// 4. Unmatched
section('4. Sections with no class in courses.json');
L.push('These stay in `data/spring2027.json` only. courses.json holds the focus electives, so the core, graduate-only, independent-study and most how-to and critical-perspectives sections land here by design. Graduate twins (ATLS 5xxx) are listed under their own code.', '');
const byClass = groupBy(unmatched, ({ r, reason }) => (reason.startsWith('no class') ? r.courseCode : `${r.courseCode} "${r.title}"`));
const rows = [...byClass].sort(([a], [b]) => a.localeCompare(b));
for (const [k, items] of rows) {
  const recs = items.map((i) => i.r);
  const cats = [...new Set(recs.map((r) => r.category).filter(Boolean))].join('/') || 'no category';
  const src = [...new Set(recs.map((r) => r.source))].join('/');
  const t = [...new Set(recs.map((r) => r.title))];
  const secs = secList(recs).length > 60 ? `${recs[0].section} to ${recs[recs.length - 1].section}` : secList(recs);
  L.push(`- **${k}**${items[0].reason.startsWith('no class') && t.length === 1 ? ` ${t[0]}` : ''}: ${recs.length} section(s) (${secs}); ${cats}; ${src}${items[0].reason.startsWith('no class') ? '' : `; ${items[0].reason}`}`);
}
const near = unmatched.filter(({ reason }) => !reason.startsWith('no class'));
L.push('', `${rows.length} class groups, ${unmatched.length} sections. ${near.length} of those sections share a code with a class in courses.json but have no matching title, so they may need a class added or a title fixed: ${[...new Set(near.map(({ r }) => `${r.courseCode} "${r.title}"`))].join('; ') || 'none'}.`);

// 5. Ambiguous times
section('5. Ambiguous times');
L.push('The sheet posts times with no AM/PM, so every 24-hour value from the sheet is inferred (hours 8-11 AM, 12 and 1-7 PM; see `parse-atlas-sheet.mjs`). A time is listed here when that rule was leaned on in a way that could be wrong. "Backed by pull" means the class search gives the same start and end, which settles it.', '');
const amb = merged.filter((r) => r.timeFlags.length);
const unbacked = amb.filter((r) => !r.timeConfirmedByPull);
L.push(`${amb.length} sections flagged; ${amb.length - unbacked.length} backed by the pull; **${unbacked.length} not backed**${unbacked.length ? ' (' + unbacked.map((r) => r.key).join(', ') + ')' : ''}. Graduate twins count as their own sections, so the count is higher than the sheet's 29 flagged rows.`, '');
for (const [flag, recs] of groupBy(amb.flatMap((r) => r.timeFlags.map((f) => ({ f, r }))), (x) => x.f)) {
  L.push(`- **${flag}** (${recs.length}): ${recs.map(({ r }) => `${r.key} "${r.time}"${r.timeConfirmedByPull ? '' : ' [NOT BACKED]'}`).join('; ')}`);
}

// 6. Cross-check of matching against the pull's own class ids
section('6. Cross-check: my class match vs the pull\'s own courseId');
const pullId = new Map(pull.map((p) => [`${p.code}-${p.section}`, p.courseId]));
const disagree = [...matched].filter(([k, course]) => pullId.get(k) && pullId.get(k) !== course.id);
const pullMapped = pull.filter((p) => p.courseId && !matched.has(`${p.code}-${p.section}`));
L.push(`Sections matched to a different class than the pull picked: ${disagree.length}${disagree.length ? ' (' + disagree.map(([k, cc]) => `${k}: mine ${cc.id}, pull ${pullId.get(k)}`).join('; ') + ')' : ''}.`);
L.push(`Sections the pull mapped to a class but my match left unmatched: ${pullMapped.length}${pullMapped.length ? ' (' + pullMapped.map((p) => `${p.code}-${p.section}`).join(', ') + ')' : ''}.`);

writeFileSync(here('../../docs/spring2027-conflicts.md'), L.join('\n') + '\n');
console.log('Wrote docs/spring2027-conflicts.md');
